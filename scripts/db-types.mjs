// Generates src/lib/types/supabase.types.ts from the local Supabase database.
// Run with `pnpm db:types` (needs `supabase start`).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';

const OUT = 'src/lib/types/supabase.types.ts';
const HEADER = '// Generated by `pnpm db:types` from the local database. Do not edit by hand.\n\n';

const types = execFileSync(
	'pnpm',
	['exec', 'supabase', 'gen', 'types', 'typescript', '--local', '--schema', 'public'],
	{ encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], shell: process.platform === 'win32' }
);

// The CLI emits unformatted code; format it so diffs stay readable.
const formatted = await format(HEADER + types, {
	...(await resolveConfig(OUT)),
	filepath: OUT,
	endOfLine: 'lf'
});

// Only written once the CLI succeeded, so a failure never leaves an empty file.
writeFileSync(OUT, formatted);
console.log(`Wrote ${OUT}`);
